"""
src/benchmarks/metrics.py

Quantitative evaluation metrics for Phase 4 benchmarking:
1. Directional Accuracy (DA) — Research Paper 4 (Wu et al. 2026).
2. Profit Uplift (%) & Cost Reduction (%) — Research Paper 3 (Wang et al.).
3. Statistical forecast accuracy (MAE, RMSE, R², MAPE).
"""

from __future__ import annotations

from typing import Any, Sequence
import numpy as np


def calculate_directional_accuracy(
    y_true: Sequence[float],
    y_pred: Sequence[float],
) -> float:
    """Calculate Directional Accuracy (DA) percentage between true and predicted series.

    Formula (Wu et al. 2026):
        DA = (1 / (N - 1)) * Σ 1[sign(y_{t+1} - y_t) == sign(ŷ_{t+1} - y_t)] * 100%

    Args:
        y_true: Observed ground truth time series values.
        y_pred: Predicted time series values.

    Returns:
        Directional accuracy percentage (0.0 to 100.0).

    Raises:
        ValueError: If series lengths do not match or have fewer than 2 points.
    """
    if len(y_true) != len(y_pred):
        raise ValueError(
            f"Series length mismatch: len(y_true)={len(y_true)} != len(y_pred)={len(y_pred)}"
        )
    if len(y_true) < 2:
        raise ValueError("Need at least 2 data points to compute directional changes.")

    y_t = np.asarray(y_true, dtype=float)
    y_p = np.asarray(y_pred, dtype=float)

    diff_true = y_t[1:] - y_t[:-1]
    diff_pred = y_p[1:] - y_p[:-1]

    # Matching directions (including matching zeros)
    sign_true = np.sign(diff_true)
    sign_pred = np.sign(diff_pred)

    correct_direction = (sign_true == sign_pred).sum()
    total_steps = len(diff_true)

    return float((correct_direction / total_steps) * 100.0)


def calculate_profit_uplift(
    ai_net_profit: float,
    baseline_net_profit: float,
) -> float:
    """Calculate percentage profit uplift of AI schedule over a baseline policy.

    Formula:
        Uplift (%) = ((Profit_AI - Profit_Baseline) / |Profit_Baseline|) * 100%

    Args:
        ai_net_profit: Net profit generated by AI MILP solver ($).
        baseline_net_profit: Net profit generated by baseline policy ($).

    Returns:
        Percentage profit uplift. Positive means AI performed better.
    """
    if abs(baseline_net_profit) < 1e-9:
        return 0.0
    return float(((ai_net_profit - baseline_net_profit) / abs(baseline_net_profit)) * 100.0)


def calculate_cost_reduction(
    baseline_cost: float,
    ai_cost: float,
) -> float:
    """Calculate percentage voyage cost reduction of AI schedule over a baseline.

    Formula:
        Reduction (%) = ((Cost_Baseline - Cost_AI) / Cost_Baseline) * 100%

    Args:
        baseline_cost: Total voyage expenses of baseline ($).
        ai_cost: Total voyage expenses of AI schedule ($).

    Returns:
        Percentage cost reduction. Positive means AI was cheaper.
    """
    if baseline_cost <= 0:
        return 0.0
    return float(((baseline_cost - ai_cost) / baseline_cost) * 100.0)


def calculate_forecast_errors(
    y_true: Sequence[float],
    y_pred: Sequence[float],
) -> dict[str, float]:
    """Calculate statistical error metrics (MAE, RMSE, R², MAPE).

    Args:
        y_true: Observed ground truth time series values.
        y_pred: Predicted time series values.

    Returns:
        Dictionary with keys: 'mae', 'rmse', 'r2', 'mape'.
    """
    if len(y_true) != len(y_pred):
        raise ValueError("Series lengths must match.")
    if len(y_true) == 0:
        return {"mae": 0.0, "rmse": 0.0, "r2": 0.0, "mape": 0.0}

    y_t = np.asarray(y_true, dtype=float)
    y_p = np.asarray(y_pred, dtype=float)

    mae = float(np.mean(np.abs(y_t - y_p)))
    rmse = float(np.sqrt(np.mean((y_t - y_p) ** 2)))

    # R2 score
    ss_res = np.sum((y_t - y_p) ** 2)
    ss_tot = np.sum((y_t - np.mean(y_t)) ** 2)
    r2 = float(1.0 - (ss_res / ss_tot)) if ss_tot > 1e-9 else 0.0

    # MAPE
    non_zero = np.abs(y_t) > 1e-6
    if np.any(non_zero):
        mape = float(np.mean(np.abs((y_t[non_zero] - y_p[non_zero]) / y_t[non_zero])) * 100.0)
    else:
        mape = 0.0

    return {
        "mae": round(mae, 4),
        "rmse": round(rmse, 4),
        "r2": round(r2, 4),
        "mape": round(mape, 2),
    }
